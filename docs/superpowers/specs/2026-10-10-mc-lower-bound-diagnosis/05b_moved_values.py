"""Build moved_values.txt from 05_bit_identity_before.out (0d1e4133 library code) and 05_bit_identity_after.out
(the statistical lower-bound check). Exits non-zero if any line that PRICED before differs after."""
import sys
from pathlib import Path

HERE = Path(__file__).parent
before = (HERE / "05_bit_identity_before.out").read_text().splitlines()
after = (HERE / "05_bit_identity_after.out").read_text().splitlines()
assert len(before) == len(after), (len(before), len(after))


def split(line):
    if line.startswith("barrier "):
        cell, value = line.split(": ", 1)
    else:
        cell, value = line[:48].rstrip(), line[48:].strip()
    return cell, value


PINNED = {
    "flat S90 put T=1d lag0d mult1 anti256":
        "test_euro_mc_lower_bound_statistical.py::test_one_day_deep_itm_put_prices_its_estimate[90.0-...]",
    "flat S75 put T=1d lag0d mult1 anti256":
        "test_euro_mc_lower_bound_statistical.py::test_one_day_deep_itm_put_prices_its_estimate[75.0-...]",
}
for form in ("dated", "numeric"):
    for spot in ("90", "75"):
        PINNED[f"barrier down_in_put {form} carried=True before S{spot}"] = (
            "test_euro_mc_lower_bound_statistical.py::test_carried_knock_in_put_the_day_before_prices_through_the_"
            f"barrier_mc[{form}-{spot}.0-...]"
            + ("; test_expiry_carried_knock_in.py::test_a_carried_knock_in_the_day_before_is_on_the_settled_branch"
               "[mc-down_in_put-90] (|before - settled| <= one-day sd)" if spot == "90" else ""))

moved, passing_moved, unchanged, still_raised = [], [], 0, []
for b, a in zip(before, after):
    cb, vb = split(b)
    ca, va = split(a)
    assert cb == ca, (cb, ca)
    if vb == va:
        unchanged += 1
        if vb.startswith("RAISED"):
            still_raised.append(cb)
    elif vb.startswith("RAISED") and not va.startswith("RAISED"):
        old = vb.split("Price (")[1].split(")")[0]
        moved.append((cb, old, va, PINNED.get(cb, "05_bit_identity.py grid (unpinned)")))
    else:
        passing_moved.append((cb, vb, va))

out = [
    "# Moved values: EuropeanMCEngine lower-bound check made statistical (W13a, user decision 2026-10-10)",
    "# Refuse only if price < bound - max(Tolerance.PRECISION, 4 * std_error); the estimator is unchanged.",
    "# Source: 05_bit_identity.py run on 0d1e4133 library code (05_bit_identity_before.out) and on the branch",
    "# (05_bit_identity_after.out); this file is generated by 05b_moved_values.py.",
    f"# Measured lines: {len(before)}. Passing prices moved: {len(passing_moved)}. Unchanged lines: {unchanged}.",
    f"# raised -> price: {len(moved)}. Still raised after: {len(still_raised)}.",
    "# 'old' is the refused estimate as the PricingError printed it (6 decimals); 'new' is the returned price (repr).",
    "# The returned price IS the estimate the old engine computed and refused (no estimator change).",
    "#",
    "# cell | old (raised) -> new | pinned by",
]
# pinned cells first
for cell, old, new, pin in sorted(moved, key=lambda m: (m[3].startswith("05_"), m[0])):
    out.append(f"{cell} | RAISED (estimate {old}) -> {new} | {pin}")
if passing_moved:
    out.append("# !!! PASSING PRICES MOVED:")
    out += [f"{c} | {o} -> {n}" for c, o, n in passing_moved]
(HERE / "moved_values.txt").write_text("\n".join(out) + "\n")
print("\n".join(out[:12]))
sys.exit(1 if passing_moved else 0)
